#!/usr/bin/env python3
"""
Scaffold a complete token engineering set from a tokens JSON (design-md skill).

Input schema (accepts this skill's / NexusChain Explorer style; flat hex also OK):

{
  "name": "Acme Explorer",
  "color":      { "bg": {"value": "#0A0C10", "role": "页面背景"}, ... },   # default (dark) theme
  "colorLight": { "bg": {"value": "#F7F8FA"}, ... },                       # optional light overrides
  "font":   { "family": {...}, "size": {...}, "weight": {...} },           # optional
  "radius": { "sm": "8px", ... }, "spacing": {...}, "zIndex": {...}, "shadow": {...}
}

Outputs into --out DIR:
  tokens.css            dual-form tokens: --x: #hex;  --x-rgb: r g b;
                        (light theme under [data-theme='light'] — critical for Tailwind alpha)
  design-tokens.json    normalized, rgb channels filled
  tailwind.extend.js    paste-ready theme.extend object (colors → rgb(var(--x-rgb) / <alpha-value>))
  preview.html          self-contained visual catalog (theme toggle included)
  contrast-report.txt   auto WCAG checks (exit nonzero on FAIL unless --no-fail)

Usage:
  python3 scaffold.py --tokens templates/design-tokens.example.json --out ./design-out
"""
