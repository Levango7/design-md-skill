import wcag  # noqa: E402  (same-dir module: hex_to_rgb / contrast_ratio / auto_pairs / check_theme)

HEX_RE = r"^#[0-9a-fA-F]{6}$"


def norm_color_map(section) -> dict:
    """section → {token: {"value": "#rrggbb", "rgb": "r g b", "role"?: str}}"""
    out = {}
    if not isinstance(section, dict):
        return out
    for key, spec in section.items():
        value = role = None
        if isinstance(spec, str) and spec.strip().startswith("#"):
            value = spec.strip()
        elif isinstance(spec, dict) and isinstance(spec.get("value"), str):
            value = spec["value"].strip()
            role = spec.get("role")
        if not value:
            continue
        import re

        if not re.fullmatch(HEX_RE, value):
            print(f"  (skip non-hex token {key}: {value!r})", file=sys.stderr)
            continue
        item = {"value": value.upper()}
        r, g, b = wcag.hex_to_rgb(value)
        item["rgb"] = f"{r} {g} {b}"
        if role:
            item["role"] = role
        out[key] = item
    return out


def norm_flat(section) -> dict:
    """For font/radius/spacing/... sections → {k: scalar string/number}."""
    out = {}
    if not isinstance(section, dict):
        return out
    for key, spec in section.items():
        if isinstance(spec, (str, int, float)):
            out[key] = spec
        elif isinstance(spec, dict) and isinstance(spec.get("value"), (str, int, float)):
            out[key] = spec["value"]
    return out


def find_key(data: dict, *names):
    for n in names:
        if n in data and isinstance(data[n], dict):
            return data[n]
    return None


def build_tokens_css(name: str, dark: dict, light: dict, extras: dict, date: str) -> str:
    lines = [
        f"/* {name} — design tokens (generated by design-md scaffold.py on {date}) */",
        "/* tokens.css 是权威来源（source of truth）；改色必须同步 design-tokens.json 并重跑 wcag.py */",
        "",
        ":root {",
    ]
    for key, item in dark.items():
        lines.append(f"  --{key}: {item['value'].lower()};")
        lines.append(f"  --{key}-rgb: {item['rgb']};")
    for section, prefix in (
        ("font_family", "--font-"),
        ("font_size", "--text-"),
        ("font_weight", "--weight-"),
        ("radius", "--radius-"),
        ("spacing", "--space-"),
        ("zindex", "--z-"),
        ("shadow", "--shadow-"),
    ):
        for key, value in extras.get(section, {}).items():
            lines.append(f"  {prefix}{key}: {value};")
    lines.append("}")
    if light:
        lines += ["", "[data-theme='light'] {", "  /* 仅覆盖差异项，其余继承 :root（CSS 级联） */"]
        for key, item in light.items():
            lines.append(f"  --{key}: {item['value'].lower()};")
            lines.append(f"  --{key}-rgb: {item['rgb']};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def build_tailwind_extend(dark: dict, extras: dict) -> str:
    colors = {k: f"rgb(var(--{k}-rgb) / <alpha-value>)" for k in dark}
    payload = {"colors": colors}
    if extras.get("font_family"):
        payload["fontFamily"] = {k: f"var(--font-{k})" for k in extras["font_family"]}
    if extras.get("font_size"):
        payload["fontSize"] = {k: f"var(--text-{k})" for k in extras["font_size"]}
    if extras.get("font_weight"):
        payload["fontWeight"] = {k: f"var(--weight-{k})" for k in extras["font_weight"]}
    if extras.get("radius"):
        payload["borderRadius"] = {k: f"var(--radius-{k})" for k in extras["radius"]}
    if extras.get("spacing"):
        payload["spacing"] = {k: f"var(--space-{k})" for k in extras["spacing"]}
    if extras.get("zindex"):
        payload["zIndex"] = {k: f"var(--z-{k})" for k in extras["zindex"]}
    if extras.get("shadow"):
        payload["boxShadow"] = {k: f"var(--shadow-{k})" for k in extras["shadow"]}
    body = json.dumps(payload, indent=2, ensure_ascii=False)
    return (
        "// Generated by design-md scaffold.py — merge into tailwind.config.js theme.extend\n"
        "// 颜色一律走 rgb(var(--x-rgb) / <alpha-value>)，否则透明度修饰符静默失效（见 design-md lessons #1）\n"
        f"module.exports = {body};\n"
    )


